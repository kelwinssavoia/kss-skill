import assert from 'node:assert/strict'
import { test } from 'node:test'

import { closeReason, FINISHED_QUIET_MS, IDLE_MS } from './closer.ts'
import { claudeFirstPrompt, phaseOfPrompt, withEnded, withOpened } from './history.ts'

const NOW = 10_000_000
const ago = (ms: number) => NOW - ms
const activity = (quietMs: number, stillMs = quietMs) => ({ startedAt: ago(IDLE_MS * 3), lastInput: ago(quietMs), lastOutput: ago(stillMs) })
const phase = { kind: 'phase' as const, phase: 'review' }
const board = (o: object = {}) => ({ phase: 'review', isPhaseFinished: false, isClosed: false, ...o })

test('a phase whose Next moved on closes once it went quiet; a running one does not', () => {
  assert.equal(closeReason(phase, activity(FINISHED_QUIET_MS + 1000), 0, board({ isPhaseFinished: true }), NOW), 'finished')
  assert.equal(closeReason(phase, activity(FINISHED_QUIET_MS + 1000), ago(2000), board({ isPhaseFinished: true }), NOW), null)
  assert.equal(closeReason(phase, activity(FINISHED_QUIET_MS + 1000), 0, board(), NOW), null)
  // The terminal of another phase than the board's is not "finished" — only idle.
  assert.equal(closeReason({ kind: 'phase', phase: 'execute' }, activity(FINISHED_QUIET_MS + 1000), 0, board({ isPhaseFinished: true }), NOW), null)
})

test('anything idle for 5 minutes closes — unless its screen still moves (a tool runs, a subagent is awaited)', () => {
  assert.equal(closeReason({ kind: 'chat', phase: null }, activity(IDLE_MS + 1000), 0, null, NOW), 'idle')
  assert.equal(closeReason({ kind: 'chat', phase: null }, activity(IDLE_MS + 1000, 1000), 0, null, NOW), null)
  assert.equal(closeReason(phase, activity(IDLE_MS + 1000), ago(60_000), board(), NOW), null)
  assert.equal(closeReason({ kind: 'shell', phase: null }, activity(IDLE_MS * 2), 0, null, NOW), null)
})

test('the first ending recorded wins; reopening a conversation makes it live again', () => {
  let s = withOpened({}, { cwd: '/wt', kind: 'phase', phase: 'review', title: 'review · Claude', conversation: 'c1', args: '073-x --loop' }, 'T0')
  s = withEnded(s, 'c1', 'cleared', 'T1')
  s = withEnded(s, 'c1', 'exited', 'T2')
  assert.equal(s.c1!.end, 'cleared')
  s = withOpened(s, { cwd: '/wt', kind: 'phase', phase: 'review', title: 'review · Claude', conversation: 'c1' }, 'T3')
  assert.equal(s.c1!.end, null)
  assert.equal(s.c1!.args, '073-x --loop')
  assert.equal(withEnded(s, null, 'idle', 'T4'), s)
})

test('a transcript names its phase by the command it started with', () => {
  const line = (content: unknown, extra = {}) => JSON.stringify({ type: 'user', timestamp: '2026-10-27T20:53:28.611Z', message: { role: 'user', content }, ...extra })
  const text = [
    JSON.stringify({ type: 'mode', mode: 'normal' }),
    line('<command-name>/clear</command-name><command-args></command-args>'),
    line('Caveat: the messages below were generated by the user while running local commands.', { isMeta: true }),
    line('<command-message>kss:kss-review</command-message>\n<command-name>/kss:kss-review</command-name>\n<command-args>073-x --loop --app</command-args>'),
  ].join('\n')
  const first = claudeFirstPrompt(text)
  assert.deepEqual(first, { prompt: '/kss:kss-review 073-x --loop --app', at: '2026-10-27T20:53:28.611Z' })
  assert.deepEqual(phaseOfPrompt(first!.prompt), { phase: 'review', args: '073-x --loop' })
  assert.equal(phaseOfPrompt('why does the pull fail?'), null)
  assert.deepEqual(claudeFirstPrompt(line([{ type: 'text', text: 'why does the pull fail?' }])), { prompt: 'why does the pull fail?', at: '2026-10-27T20:53:28.611Z' })
})
